import { writeToFile, generateSignedUrl } from './s3-service.mjs';
import { sendEmailProcess } from './ses-service.mjs';

export const sendNotification = async (Metadata) => {
    try {
        // create output file
        const uid = Metadata.uid;
        const email = Metadata.email;
        const outputCsvKey = `output/output${uid}.csv`;
        const outputCsv = await writeToFile(outputCsvKey, '', Metadata);

        const csvLink = await generateSignedUrl(`output/output${uid}.csv`);
        const htmlBody = `
        <html>
            <body>
                <p>Hello!</p>
                <p>I'm delighted to inform you that the process of generating the file is complete.</p>
                <p>Here's the link you've been waiting for <a href="${csvLink}">Output CSV Link</a></p>
                <p>With this link, you can now access and download the file. 
                Please keep in mind that the link will remain active for 24 hours, allowing you ample time to retrieve the file. 
                After that, the link will expire and no longer provide access.</p>
                <p>Thank you for using PPGPT!</p>
            </body>
        </html>
        `;
        const subject = 'CSV generated by PPGPT';
        await sendEmailProcess(email, subject, htmlBody);
        
    } catch (error) {
        console.error('Error sending notification:', error);
        throw error;
    }
}   